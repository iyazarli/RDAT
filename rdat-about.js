  const copy = value => JSON.parse(JSON.stringify(value));
  const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  function matchesCategory(value, previous) {
    const fields = ['id', 'slug', 'label', 'eyebrow', 'title', 'intro', 'ctaLabel', 'ctaHref'];
    return fields.every(key => value[key] === previous[key])
      && value.blocks?.length === previous.blocks.length
      && value.blocks.every((block, index) => ['id', 'title', 'text', 'tag', 'imageUrl', 'url', 'gallery'].every(key =>
        equal(block[key] ?? (key === 'gallery' ? [] : ''), previous.blocks[index][key] ?? (key === 'gallery' ? [] : ''))));
  }
  function apply(config, force = false) {
    const next = copy(config || {});
    const index = next.categories?.findIndex(item => item.slug === 'about');
    if (index >= 0 && (force || legacyCategories.some(old => matchesCategory(next.categories[index], old)))) {
      next.categories[index] = { ...next.categories[index], ...copy(category), showInMenu: next.categories[index].showInMenu };
    }
    if (next.home?.about && (force || legacyHomes.some(old => equal(next.home.about, old)))) next.home.about = copy(home);
    // Kayıtlı eski metinlerde de takımın resmi kısaltmasını göster.
    const textFields = new Set(['title', 'text', 'intro', 'ctaLabel', 'lede', 'description', 'label', 'question', 'answer']);
    function correctNames(value) {
      if (!value || typeof value !== 'object') return;
      for (const [key, item] of Object.entries(value)) {
        if (typeof item === 'string' && textFields.has(key)) value[key] = item.replace(/RDAT/g, 'R.D.A.T.');
        else if (item && typeof item === 'object') correctNames(item);
      }
    }
    const aboutCategory = next.categories?.find(item => item.slug === 'about');
    for (const block of aboutCategory?.blocks || []) {
      const replacement = category.blocks.find(item => item.id === block.id);
      const previousImage = legacyCategories.flatMap(item => item.blocks).find(item => item.id === block.id)?.imageUrl;
      if (replacement && (!block.imageUrl || block.imageUrl === previousImage)) block.imageUrl = replacement.imageUrl;
    }
    correctNames(next);
    return next;
  }
